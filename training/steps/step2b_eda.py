"""Step 2b - Exploratory Data Analysis on both datasets (plan v2 Section 6).

USAGE
  python training/steps/step2b_eda.py                                  # OFF (off_clean) + USDA (usda_labeled) if present
  python training/steps/step2b_eda.py --off data/sample/products_sample.csv --usda data/sample/usda_branded_sample.zip
  python training/steps/step2b_eda.py --sample 200000                   # cap rows for speed on the full export

Writes
  reports/figures/eda_*.png         plots E1-E11
  reports/tables/eda_*.csv          the statistical summaries
  reports/eda_findings.md           numbers + one-line findings under each plot (copy into the report)
Run after step2 (OFF) and step3/step3b (USDA). Each part is skipped with a message when its input is missing.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "runtime" / "src"))
from nutriscan import config, eda  # noqa: E402
from nutriscan.data import clean_products  # noqa: E402
from nutriscan.external import normalize_usda, read_usda_branded  # noqa: E402
from nutriscan.usda import label_usda, mapping_table, read_usda_nutrients  # noqa: E402

TIER = ["good", "medium", "poor"]
NUTS = config.NUTRIENT_COLS




class Findings:
    def __init__(self):
        self.lines = ["# EDA findings (auto-generated by training/steps/step2b_eda.py)", "",
                      "Numbers below are computed from the data that was passed in. Re-run after every data refresh.", ""]

    def h(self, text):
        self.lines += ["", f"## {text}", ""]

    def fig(self, path: Path, finding: str):
        self.lines += [f"![{path.stem}](figures/{path.name})", "", f"- {finding}", ""]

    def table(self, df: pd.DataFrame, n=12):
        self.lines += [df.head(n).to_markdown(index=False) if hasattr(df, "to_markdown") else df.head(n).to_string(), ""]

    def text(self, t):
        self.lines.append(t)

    def write(self):
        out = config.REPORTS / "eda_findings.md"
        out.write_text("\n".join(self.lines), encoding="utf-8")
        return out


def save(tbl: pd.DataFrame, name: str, index=False):
    config.TABLES.mkdir(parents=True, exist_ok=True)
    tbl.to_csv(config.TABLES / f"{name}.csv", index=index)


def pct(x) -> str:
    return f"{100 * x:.1f}%"


def off_eda(raw: pd.DataFrame, f: Findings, sample: int) -> pd.DataFrame:
    f.h("Open Food Facts (D1)")
    save(eda.overview(raw, "OFF raw"), "eda_off_overview")
    save(eda.dtypes_table(raw), "eda_off_dtypes")
    m = eda.missing_table(raw)
    save(m, "eda_off_missing")
    p = eda.plot_missing(raw, "eda_E1_off_missing", "E1  OFF: missing values per column")
    worst = m.iloc[0]
    f.fig(p, f"{len(raw):,} rows before cleaning. Most incomplete column: `{worst.column}` ({worst.missing_pct:.1f}% missing). "
             f"NOVA missing: {pct(raw['nova_group'].isna().mean()) if 'nova_group' in raw else 'n/a'}, "
             f"Nutri-Score missing: {pct(raw['nutriscore_grade'].isna().mean()) if 'nutriscore_grade' in raw else 'n/a'}.")

    df = clean_products(raw)
    if sample and len(df) > sample:
        df = df.sample(sample, random_state=config.RANDOM_STATE)
        f.text(f"_Plots after cleaning use a random sample of {sample:,} rows._")
    df = eda.add_text_features(df)
    f.text(f"After the Section 5 cleaning rules: {len(df):,} rows (dropped empty ingredients and duplicates).")

    num = eda.numeric_summary(df, ["n_ingredients", "n_e_numbers", "n_markers", *NUTS])
    save(num, "eda_off_numeric_summary", index=True)
    f.text("**Numeric summary**"); f.table(num.reset_index().rename(columns={"index": "feature"}), 20)

    nova = df["nova_group"].dropna().astype(int)
    cb = eda.class_balance(nova); save(cb, "eda_off_nova_balance")
    p = eda.plot_class_distribution(nova, "eda_E2_off_nova", "E2  OFF: NOVA group distribution", colors=eda.NOVA_COLORS)
    f.fig(p, f"NOVA is heavily imbalanced: NOVA 4 = {cb.set_index('class').pct.get(4, 0):.1f}%, NOVA 2 = "
             f"{cb.set_index('class').pct.get(2, 0):.1f}%; imbalance ratio {eda.imbalance_ratio(nova):.0f}:1. "
             f"Macro-F1 is therefore the headline metric and imbalance handling is compared in step6.")
    if "health_tier" in df:
        tier = df.loc[df["health_tier"].isin(TIER), "health_tier"]
        cbt = eda.class_balance(tier); save(cbt, "eda_off_tier_balance")
        p = eda.plot_class_distribution(tier, "eda_E2_off_tier", "E2  OFF: health tier (from Nutri-Score)", order=TIER,
                                        colors=eda.TIER_COLORS)
        f.fig(p, f"Health tier is less skewed (ratio {eda.imbalance_ratio(tier):.1f}:1); 'poor' is the largest class "
                 f"({cbt.set_index('class').pct.get('poor', 0):.1f}%).")

    lab = df[df["nova_group"].notna()].copy()
    lab["nova_group"] = lab["nova_group"].astype(int)
    gs = eda.group_summary(lab, "nova_group", ["n_ingredients", "n_e_numbers", "n_markers", "sugars_100g"])
    save(gs, "eda_off_by_nova", index=True)
    p = eda.plot_box_by(lab, ["n_ingredients", "n_e_numbers", "n_markers"], "nova_group", "eda_E3_off_counts_by_nova",
                        "E3  Ingredient / additive counts by NOVA group")
    med = lab.groupby("nova_group")["n_ingredients"].median()
    f.fig(p, f"Median ingredient count rises from {med.iloc[0]:.0f} (NOVA {med.index[0]}) to {med.iloc[-1]:.0f} "
             f"(NOVA {med.index[-1]}); E-numbers and marker words appear almost only in NOVA 4, which is why a simple "
             f"keyword rule is a strong baseline (and why NOVA labels partly leak, Section 4).")

    ta = eda.top_additives(df["ingredients_norm"]); save(ta, "eda_off_top_additives")
    ta4 = eda.top_additives(lab.loc[lab["nova_group"] == 4, "ingredients_norm"]); save(ta4, "eda_off_top_additives_nova4")
    p = eda.plot_top_table(ta4, "additive", "eda_E4_off_top_additives_nova4", "E4  Top additives / markers in NOVA 4 products")
    if len(ta4):
        f.fig(p, f"Most common in NOVA 4: `{ta4.iloc[0].additive}` ({ta4.iloc[0].pct:.1f}% of NOVA 4 products), then "
                 + ", ".join(f"`{a}`" for a in ta4.additive.iloc[1:5]) + ".")

    p = eda.plot_top_ingredients_by_class(lab, "nova_group", "eda_E5_off_top_ingredients_by_nova",
                                          "E5  Most frequent ingredients per NOVA group")
    f.fig(p, "Distinct vocabularies per class (whole foods in NOVA 1, single culinary ingredients in NOVA 2, salt/sugar/oil "
             "additions in NOVA 3, syrups, flavourings and emulsifiers in NOVA 4) justify TF-IDF text features.")

    if "category" in df:
        p = eda.plot_counts(df["category"], "eda_E6_off_categories", "E6  OFF: products per food group")
        f.fig(p, f"{df['category'].nunique()} food groups; category missing for {pct(df['category'].isna().mean())} of rows "
                 f"(kept for NOVA/tier, dropped for the category model). Rare groups: "
                 + ", ".join(df['category'].value_counts().tail(2).index.astype(str)) + ".")
        p = eda.plot_share_by_category(lab.dropna(subset=["category"]), "category", "nova_group", "eda_E6_off_nova_share_by_category",
                                       "E6  NOVA share within each food group", colors=eda.NOVA_COLORS)
        share4 = (pd.crosstab(lab["category"], lab["nova_group"], normalize="index")[4] if 4 in lab["nova_group"].values
                  else pd.Series(dtype=float)).sort_values()
        if len(share4):
            f.fig(p, f"Most ultra-processed group: {share4.index[-1]} ({pct(share4.iloc[-1])} NOVA 4); least: "
                     f"{share4.index[0]} ({pct(share4.iloc[0])}). Alternatives are searched within the same group.")

    nuts = [c for c in NUTS if c in df and df[c].notna().any()]
    if nuts:
        p = eda.plot_nutrients(df, nuts, "eda_E7_off_nutrient_hist", "E7  OFF: nutrient distributions (per 100 g, clipped at p99)")
        out = {c: int((df[c] > 100).sum()) for c in nuts if c != "energy_kcal_100g"}
        f.fig(p, "Nutrients are right-skewed; physically impossible values (>100 g per 100 g) found: "
                 + ", ".join(f"{k}={v}" for k, v in out.items()) + ". These are dropped/capped in preprocessing (Section 5).")
        p = eda.plot_corr(df, nuts + ["n_ingredients", "n_e_numbers"], "eda_E7_off_corr", "E7  Spearman correlation")
        f.fig(p, "Nutrients that move together (e.g. energy with fat) and the weak link between ingredient counts and nutrients "
                 "show that processing (NOVA) and nutrient profile (Nutri-Score) are different targets.")
        if "health_tier" in df:
            p = eda.plot_box_by(df[df["health_tier"].isin(TIER)], nuts[:4], "health_tier", "eda_E8_off_nutrients_by_tier",
                                "E8  Nutrients by health tier", order=TIER)
            f.fig(p, "Sugar, saturated fat and salt increase from 'good' to 'poor', confirming the derived tier behaves as expected.")

    p = eda.plot_box_by(lab, ["sugar_pos", "fat_pos"], "nova_group", "eda_E9_off_position_by_nova",
                        "E9  Position of first sugar / fat source (0 = absent)")
    f.fig(p, "Sugar and fat sources appear earlier in NOVA 3-4 lists; ingredient order carries signal (used in rf_features).")

    if "countries" in df or "lang" in df:
        col = "lang" if "lang" in df else "countries"
        p = eda.plot_counts(df[col], "eda_E11_off_language", f"E11  OFF: products by {col}")
        top = df[col].value_counts(normalize=True)
        f.fig(p, f"Data is dominated by `{top.index[0]}` ({pct(top.iloc[0])}); results are reported per language/region in the "
                 f"fairness section.")
    if "countries" in df:
        first = df["countries"].astype(str).str.split(",").str[0].str.replace("en:", "")
        p = eda.plot_counts(first, "eda_E11_off_countries", "E11  OFF: first listed country")
        top = first.value_counts(normalize=True)
        f.fig(p, f"Top country: {top.index[0]} ({pct(top.iloc[0])}). Over-represented regions are a fairness limitation.")
    return df


def usda_eda(usda: pd.DataFrame, off: pd.DataFrame | None, f: Findings, sample: int):
    f.h("USDA FoodData Central Branded (D2)")
    save(eda.overview(usda, "USDA"), "eda_usda_overview")
    save(eda.missing_table(usda), "eda_usda_missing")
    p = eda.plot_missing(usda, "eda_E1_usda_missing", "E1  USDA: missing values per column")
    f.fig(p, f"{len(usda):,} USDA products with ingredients (one row per barcode, latest version).")
    mt = mapping_table(usda); save(mt, "usda_category_mapping")
    mapped = usda["category"].notna().mean()
    p = eda.plot_counts(usda["usda_category"], "eda_E6_usda_categories", "E6  USDA: top branded food categories", color="#ef6c00")
    f.fig(p, f"{usda['usda_category'].nunique():,} USDA categories; {pct(mapped)} of products map to an OFF food group "
             f"(mapping table: reports/tables/usda_category_mapping.csv).")
    p = eda.plot_counts(usda["category"], "eda_E6_usda_mapped_groups", "E6  USDA products per mapped OFF food group", color="#ef6c00")
    f.fig(p, "Mapped USDA groups give an independent category label for T3.")
    if "health_tier" in usda and usda["health_tier"].notna().any():
        tier = usda.loc[usda["health_tier"].isin(TIER), "health_tier"]
        save(eda.class_balance(tier), "eda_usda_tier_balance")
        p = eda.plot_class_distribution(tier, "eda_E2_usda_tier", "E2  USDA: health tier from USDA nutrients (Nutri-Score 2017)",
                                        order=TIER, colors=eda.TIER_COLORS)
        f.fig(p, f"{len(tier):,} USDA products get a nutrient-based tier, independent of OFF labels (imbalance "
                 f"{eda.imbalance_ratio(tier):.1f}:1).")
        nuts = [c for c in NUTS if c in usda and usda[c].notna().any()]
        p = eda.plot_nutrients(usda, nuts, "eda_E7_usda_nutrient_hist", "E7  USDA: nutrient distributions (per 100 g)")
        f.fig(p, "USDA nutrients are manufacturer-declared per 100 g; same skew as OFF.")
    u = usda.copy()
    u["ingredients_norm"] = u["ingredients_norm"] if "ingredients_norm" in u else clean_products(u)["ingredients_norm"]
    if sample and len(u) > sample:
        u = u.sample(sample, random_state=config.RANDOM_STATE)
    u = eda.add_text_features(u)
    save(eda.numeric_summary(u, ["n_ingredients", "n_e_numbers", "n_markers"]), "eda_usda_numeric_summary", index=True)
    if off is not None:
        p = eda.plot_compare(off["n_ingredients"], u["n_ingredients"], ("OFF", "USDA"), "eda_E10_off_vs_usda_n_ingredients",
                             "E10  Ingredients per product: OFF vs USDA")
        f.fig(p, f"Median ingredients per product: OFF {off['n_ingredients'].median():.0f} vs USDA {u['n_ingredients'].median():.0f}; "
                 f"USDA lists are longer and ALL-CAPS with 'contains 2% or less of' sections, so the parser normalises both "
                 f"before modelling. This shift is what the cross-dataset test measures.")
        comp = pd.DataFrame({"OFF": off["category"].value_counts(normalize=True),
                             "USDA": u["category"].value_counts(normalize=True)}).fillna(0).round(3)
        save(comp, "eda_off_vs_usda_category_mix", index=True)
        f.text("**Category mix OFF vs USDA (share of products)**"); f.table(comp.reset_index().rename(columns={"index": "group"}), 15)


def main() -> None:
    ap = argparse.ArgumentParser(description="EDA for OFF and USDA.")
    ap.add_argument("--off", default=None, help="OFF table (default: data/processed/loaded.parquet, else the sample CSV)")
    ap.add_argument("--usda", default=None, help="usda_labeled.parquet, or a USDA zip/csv (default: data/processed/usda_labeled.parquet)")
    ap.add_argument("--sample", type=int, default=200000, help="max rows for the heavier plots (0 = all)")
    a = ap.parse_args()

    f = Findings()
    off_path = config.resolve(a.off) if a.off else next((p for p in (config.PROCESSED / "loaded.parquet", config.SAMPLE_CSV)
                                                  if p.exists()), None)
    off = None
    if off_path and off_path.exists():
        raw = pd.read_parquet(off_path) if off_path.suffix == ".parquet" else pd.read_csv(off_path, dtype={"code": str})
        if off_path == config.SAMPLE_CSV or "sample" in off_path.name:
            f.text("> **SYNTHETIC SAMPLE DATA. These numbers are not results.**")
        f.text(f"OFF input: `{off_path.relative_to(config.PROJECT_ROOT) if off_path.is_relative_to(config.PROJECT_ROOT) else off_path}`")
        off = off_eda(raw, f, a.sample)
    else:
        print("OFF input not found; skipping OFF EDA (run step1 first).")

    usda_path = config.resolve(a.usda) if a.usda else config.USDA_LABELED
    if usda_path.exists():
        if usda_path.suffix == ".parquet":
            usda = pd.read_parquet(usda_path)
        else:                                          # raw zip/csv: normalise + label on the fly
            usda = label_usda(normalize_usda(read_usda_branded(usda_path)), read_usda_nutrients(usda_path))
        usda_eda(usda, off, f, a.sample)
    else:
        print(f"USDA input not found ({usda_path}); skipping USDA EDA (run step3 + step3b first).")

    out = f.write()
    print(f"Figures -> {config.FIGURES}\nTables  -> {config.TABLES}\nFindings -> {out}")


if __name__ == "__main__":
    main()
